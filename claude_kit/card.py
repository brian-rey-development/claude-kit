"""Writes every theme's welcome card into the welcome mod, which picks one by its `theme` option.

Holding all of them lets a preview session show another theme's card without touching the active one.
"""

from __future__ import annotations

import json
from collections.abc import Iterable
from pathlib import Path

from claude_kit import art
from claude_kit.jsonfile import JsonObject
from claude_kit.theme import Theme


def card(theme: Theme) -> JsonObject:
    return {
        "tagline": theme.tagline,
        "caption": theme.palette["caption"],
        "sizes": [{"width": art.width(size), "rows": size} for size in theme.art_sizes],
    }


def source(themes: Iterable[Theme]) -> str:
    cards = {theme.id: card(theme) for theme in themes}
    return "\n".join(
        [
            "// Generated by claude-kit from the themes it can find. Do not edit.",
            "import type { Card } from './card-types'",
            "",
            f"export const CARDS: Readonly<Record<string, Card>> = {json.dumps(cards, ensure_ascii=False)}",
            "",
        ]
    )


def write(themes: Iterable[Theme], out: Path) -> None:
    out.write_text(source(theme for theme in themes if theme.has_art), encoding="utf-8")
